export interface ScaffoldResult {
  success: boolean;
  appId: string;
  appPath: string;
  message: string;
  nextSteps: string[];
}

export const createNewApp = async (
  appId: string,
  appName: string,
  description: string
): Promise<ScaffoldResult> => {
  try {
    await scaffoldApp({
      appId,
      appName,
      description,
      type: "nextjs",
    });

    await updateTurboConfig(appId);
    await updateWorkspaceConfig();

    return {
      success: true,
      appId,
      appPath: `apps/${appId}`,
      message: `Successfully created ${appName}!`,
      nextSteps: [
        `cd apps/${appId}`,
        "pnpm install",
        "pnpm dev",
        `Open http://localhost:3001`,
      ],
    };
  } catch (error) {
    return {
      success: false,
      appId,
      appPath: `apps/${appId}`,
      message: error instanceof Error ? error.message : "Failed to create app",
      nextSteps: [],
    };
  }
};

