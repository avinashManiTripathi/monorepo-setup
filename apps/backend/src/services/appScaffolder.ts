// Main scaffolding function
export const scaffoldApp = async (options: ScaffoldOptions): Promise<void> => {
  const { appId, appName, type } = options;

  if (type !== "nextjs") {
    throw new Error("Only Next.js apps are supported at this time");
  }

  const monorepoRoot = getMonorepoRoot();
  const appDir = path.join(monorepoRoot, "apps", appId);

  // Check if app already exists
  if (fs.existsSync(appDir)) {
    throw new Error(`App directory already exists: apps/${appId}`);
  }

  try {
    // Create main app directory
    fs.mkdirSync(appDir, { recursive: true });

    // Create package.json
    fs.writeFileSync(
      path.join(appDir, "package.json"),
      createNextJsPackageJson(appId, appName)
    );

    // Create tsconfig.json
    fs.writeFileSync(path.join(appDir, "tsconfig.json"), createNextJsTsConfig());

    // Create next.config.mjs
    fs.writeFileSync(path.join(appDir, "next.config.mjs"), createNextConfig());

    // Create README.md
    fs.writeFileSync(path.join(appDir, "README.md"), createReadme(appName, appId));

    // Create src directory structure
    const srcDir = path.join(appDir, "src");
    fs.mkdirSync(srcDir, { recursive: true });

    // Create src/app directory
    const appSrcDir = path.join(srcDir, "app");
    fs.mkdirSync(appSrcDir, { recursive: true });

    // Create layout.tsx
    fs.writeFileSync(path.join(appSrcDir, "layout.tsx"), createLayout(appName));

    // Create page.tsx
    fs.writeFileSync(path.join(appSrcDir, "page.tsx"), createPage(appName));

    // Create globals.css
    fs.writeFileSync(path.join(appSrcDir, "globals.css"), createGlobalsCss());

    // Create public directory
    const publicDir = path.join(appDir, "public");
    fs.mkdirSync(publicDir, { recursive: true });

    console.log(`✅ Successfully scaffolded app: ${appId}`);
  } catch (error) {
    // Clean up on error
    if (fs.existsSync(appDir)) {
      fs.rmSync(appDir, { recursive: true, force: true });
    }
    throw error;
  }
};

